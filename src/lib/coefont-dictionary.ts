/**
 * ダッシュ（——、――など）を句点に変換し、CoeFont に間（ま）を作らせる。
 */
function convertDashes(text: string): string {
  return text.replace(/[\u2014\u2015\u2500\u30FC\-]{2,}/g, "。");
}

/**
 * テキスト中の漢字読み間違いを辞書で補正し、ダッシュを間に変換する。
 * CoeFont API に送る前に呼び出す。
 */
export function applyReadingDict(text: string): string {
  let result = convertDashes(text);
  for (const [kanji, reading] of READING_DICT) {
    result = result.replaceAll(kanji, reading);
  }
  return result;
}
